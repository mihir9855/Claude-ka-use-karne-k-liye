#!/usr/bin/env node
// Offline installer for shadcn-format registry items (shadcn/ui, Magic UI, React Bits).
// Reads registry JSON from local folders instead of the registry websites, writes the
// component files, merges css/cssVars into src/index.css and prints the npm dependencies.
//
// usage: node scripts/add-registry.mjs <registry> <name...|--all>
//   registry dirs come from REG_DIR (default ../.registry): shadcn/, magicui/, react-bits/
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const REG = path.resolve(process.env.REG_DIR ?? path.join(ROOT, '.registry'))
const SRC = path.join(ROOT, 'src')
const CSS = path.join(SRC, 'index.css')

const registries = {
  shadcn: { dir: 'shadcn/styles/new-york', out: 'components/ui' },
  magicui: { dir: 'magicui', out: 'components/magicui' },
  'react-bits': { dir: 'react-bits', out: 'components/react-bits' },
}

const deps = new Set()
const done = new Set()
const css = { theme: {}, light: {}, dark: {}, rules: {} }

function load(reg, name) {
  const file = path.join(REG, registries[reg].dir, `${name}.json`)
  if (!fs.existsSync(file)) throw new Error(`not found: ${reg}/${name} (${file})`)
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

function parseDep(dep, fromReg) {
  if (dep.startsWith('@magicui/')) return ['magicui', dep.slice(9)]
  if (dep.startsWith('@react-bits/')) return ['react-bits', dep.slice(12)]
  if (dep.startsWith('http')) {
    const m = dep.match(/magicui\.design\/r\/(.+)\.json$/)
    if (m) return ['magicui', m[1]]
    throw new Error(`remote registry dependency not supported: ${dep}`)
  }
  return fromReg === 'react-bits' ? ['react-bits', dep] : ['shadcn', dep]
}

function rewrite(content) {
  return content
    .replaceAll('@/registry/magicui/', '@/components/magicui/')
    .replaceAll('@/registry/new-york-v4/ui/', '@/components/ui/')
    .replaceAll('@/registry/new-york/ui/', '@/components/ui/')
}

function targetFor(reg, item, file) {
  if (file.type === 'registry:lib' || file.path.includes('lib/')) return path.join(SRC, 'lib', path.basename(file.path))
  if (file.type === 'registry:hook') return path.join(SRC, 'hooks', path.basename(file.path))
  const rel = reg === 'react-bits' ? file.path : path.basename(file.path)
  return path.join(SRC, registries[reg].out, rel)
}

function install(reg, name) {
  const key = `${reg}/${name}`
  if (done.has(key)) return
  done.add(key)
  const item = load(reg, name)
  for (const d of item.registryDependencies ?? []) {
    if (reg !== 'react-bits' && d === 'utils') continue // provided by src/lib/utils.ts
    install(...parseDep(d, reg))
  }
  for (const d of item.dependencies ?? []) deps.add(d)
  for (const d of item.devDependencies ?? []) deps.add(d)
  for (const file of item.files ?? []) {
    if (!file.content) continue
    const out = targetFor(reg, item, file)
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, rewrite(file.content))
  }
  for (const k of ['theme', 'light', 'dark']) Object.assign(css[k], item.cssVars?.[k] ?? {})
  Object.assign(css.rules, item.css ?? {})
  console.log(`+ ${key}`)
}

function block(obj, indent = '  ') {
  return Object.entries(obj)
    .map(([k, v]) => (typeof v === 'object' ? `${indent}${k} {\n${block(v, indent + '  ')}\n${indent}}` : `${indent}${k}: ${v};`))
    .join('\n')
}

function writeCss() {
  const start = '/* registry:start (generated by scripts/add-registry.mjs) */'
  const end = '/* registry:end */'
  let text = fs.readFileSync(CSS, 'utf8')
  const prev = text.includes(start) ? text.slice(text.indexOf(start), text.indexOf(end) + end.length) : ''
  // keep values from earlier runs
  const old = prev ? JSON.parse(prev.match(/\/\* data (.*) \*\//)?.[1] ?? '{}') : {}
  for (const k of Object.keys(css)) css[k] = { ...(old[k] ?? {}), ...css[k] }
  const theme = Object.fromEntries(Object.entries(css.theme).map(([k, v]) => [`--${k}`, v]))
  const parts = [
    start,
    `/* data ${JSON.stringify(css)} */`,
    Object.keys(theme).length ? `@theme inline {\n${block(theme)}\n}` : '',
    Object.keys(css.light).length ? `:root {\n${block(Object.fromEntries(Object.entries(css.light).map(([k, v]) => [`--${k}`, v])))}\n}` : '',
    Object.keys(css.dark).length ? `.dark {\n${block(Object.fromEntries(Object.entries(css.dark).map(([k, v]) => [`--${k}`, v])))}\n}` : '',
    block(css.rules, ''),
    end,
  ].filter(Boolean)
  text = prev ? text.replace(prev, parts.join('\n')) : `${text.trimEnd()}\n\n${parts.join('\n')}\n`
  fs.writeFileSync(CSS, text)
}

const [reg, ...names] = process.argv.slice(2)
if (!registries[reg] || !names.length) {
  console.error('usage: node scripts/add-registry.mjs <shadcn|magicui|react-bits> <name...|--all>')
  process.exit(1)
}
let list = names
if (names[0] === '--all') {
  const dir = path.join(REG, registries[reg].dir)
  list = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).filter((n) => {
    const t = JSON.parse(fs.readFileSync(path.join(dir, `${n}.json`), 'utf8')).type
    if (reg === 'react-bits') return n.endsWith('-TS-TW')
    return t === 'registry:ui'
  })
}
for (const n of list) install(reg, n)
writeCss()
fs.writeFileSync(path.join(ROOT, '.registry-deps.txt'), [...deps].sort().join('\n') + '\n')
console.log(`\n${done.size} items. npm dependencies written to .registry-deps.txt:\n${[...deps].sort().join(' ')}`)
